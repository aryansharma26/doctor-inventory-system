import { Router } from "express";
import { requireNoImpersonation, requirePermission } from "../../middlewares/rbac.middleware.js";
import { validate } from "../../middlewares/validate.middleware.js";
import { asyncHandler } from "../../utils/async-handler.js";
import * as controller from "./practice.controller.js";
import * as schema from "./practice.validator.js";

export const practiceRouter = Router();

practiceRouter.get(
  "/doctors",
  requirePermission("appointment.read"),
  asyncHandler(controller.listDoctors)
);
practiceRouter.get(
  "/appointments",
  requirePermission("appointment.read"),
  validate(schema.appointmentListSchema),
  asyncHandler(controller.listAppointments)
);
practiceRouter.post(
  "/appointments",
  requireNoImpersonation,
  requirePermission("appointment.manage"),
  validate(schema.createAppointmentSchema),
  asyncHandler(controller.createAppointment)
);
